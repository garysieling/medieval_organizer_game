#!/usr/bin/env python3
"""Bake the UI font table from Jacquarda Bastarda 9 (OFL, Google Fonts -
scripts/fonts/JacquardaBastarda9.ttf, licence in scripts/fonts/OFL.txt).

Jacquarda is a pixel blackletter on a 13px grid - its nominal raster is
13px tall and renders crisply only at that size. At the game's old 5x7
metric blackletter is illegible, so the face is baked at its native
size, condensed 20% horizontally (BOX resample + hard threshold - at
0.8x the gothic texture survives and the face still reads), into 10x13
monospace cells at an 11px advance. Output is game2-core/src/ui/glyphs.rs.
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "scripts", "fonts", "JacquardaBastarda9.ttf")
OUT = os.path.join(ROOT, "game2-core", "src", "ui", "glyphs.rs")

SIZE = 13          # the face's native crisp raster
SQUASH = 0.8       # horizontal condensation
Y0, Y1 = 4, 17     # global ink band (measured across ASCII 32-126)
CW = Y1 - Y0       # 13 rows
GW = 10            # cell columns

def bake():
    font = ImageFont.truetype(TTF, SIZE)
    glyphs = []
    for c in range(32, 127):
        im = Image.new("L", (48, 40), 0)
        ImageDraw.Draw(im).text((8, 0), chr(c), font=font, fill=255)
        im = im.resize((int(48 * SQUASH), 40), Image.BOX)
        im = im.point(lambda p: 255 if p >= 140 else 0)
        b = im.getbbox()
        rows = [0] * CW
        if b:
            ink = im.crop((b[0], Y0, min(b[2], b[0] + GW), Y1))
            w = min(b[2] - b[0], GW)
            ox = (GW - w) // 2 if w < GW else 0
            px = ink.load()
            for y in range(CW):
                for x in range(w):
                    if px[x, y]:
                        rows[y] |= 1 << (GW - 1 - ox - x)
        glyphs.append(rows)
    return glyphs

def emit(glyphs):
    lines = [
        "//! GENERATED by scripts/bake_font.py - Jacquarda Bastarda 9 (OFL),",
        "//! 13px raster condensed 20% horizontally into 10x13 cells.",
        "//! Do not edit by hand; re-run the bake.",
        "",
        "/// 10x13 glyphs for ASCII 32-126. Each char = 13 u16 rows,",
        "/// bits 9-0 = pixel columns left-to-right.",
        "pub(crate) const GLYPHS: [[u16; 13]; 95] = [",
    ]
    for i, rows in enumerate(glyphs):
        ch = chr(i + 32)
        name = "space" if i == 0 else ch
        body = ",".join(str(r) for r in rows)
        lines.append(f"    [{body}], {' ' * max(1, 62 - len(body))}// {i + 32} {name}")
    lines.append("];")
    lines.append("")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(lines))

if __name__ == "__main__":
    emit(bake())
    print("wrote", OUT)
