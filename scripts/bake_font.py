#!/usr/bin/env python3
"""Bake the UI font table from Jacquarda Bastarda 9 (OFL, Google Fonts -
scripts/fonts/JacquardaBastarda9.ttf, licence in scripts/fonts/OFL.txt).

Jacquarda is a pixel blackletter on a 13px grid - its nominal raster is
13px tall and renders crisply only at that size. The face is baked at
its native size (no condensation - a squeezed blackletter reads worse
than a wide one) into 14-column cells so the widest glyphs (m, w, @)
keep their full ink instead of cropping at the cell edge, and each
glyph carries its own advance: ink width plus a pixel of air, so the
tracking tightens up where the old fixed 11px advance spread thin
letters apart. Output is game2-core/src/engine/glyphs.rs.
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "scripts", "fonts", "JacquardaBastarda9.ttf")
OUT = os.path.join(ROOT, "game2-core", "src", "engine", "glyphs.rs")

SIZE = 13          # the face's native crisp raster
Y0, Y1 = 4, 17     # global ink band (measured across ASCII 32-126)
CW = Y1 - Y0       # 13 rows
GW = 14            # cell columns - the widest glyph must fit uncropped
GAP = 1            # pixels of air after a glyph's ink
SPACE_ADV = 5      # a word space's advance
MIN_ADV = 4        # and even a bare serif keeps a breath

def bake():
    font = ImageFont.truetype(TTF, SIZE)
    glyphs = []
    for c in range(32, 127):
        im = Image.new("L", (64, 40), 0)
        ImageDraw.Draw(im).text((8, 0), chr(c), font=font, fill=255)
        im = im.point(lambda p: 255 if p >= 128 else 0)
        b = im.getbbox()
        rows = [0] * CW
        adv = SPACE_ADV if c == 32 else MIN_ADV
        if b:
            ink_w = min(b[2] - b[0], GW)
            # a glyph wider than the cell squeezes in rather than lose
            # its right edge - rare at 14 columns, but a clipped
            # blackletter letter reads as a wrong letter entirely
            if b[2] - b[0] > GW:
                ink = im.crop((b[0], Y0, b[2], Y1)).resize(
                    (GW, CW), Image.BOX).point(lambda p: 255 if p >= 128 else 0)
            else:
                ink = im.crop((b[0], Y0, b[0] + ink_w, Y1))
            px = ink.load()
            for y in range(CW):
                for x in range(ink_w):
                    if px[x, y]:
                        rows[y] |= 1 << (GW - 1 - x)
            if c != 32:
                adv = max(MIN_ADV, ink_w + GAP)
        glyphs.append((rows, adv))
    return glyphs

def emit(glyphs):
    lines = [
        "//! GENERATED by scripts/bake_font.py - Jacquarda Bastarda 9 (OFL),",
        "//! 13px raster at native width into 14-column cells, each glyph",
        "//! with its own advance (ink width + 1px). Do not edit by hand;",
        "//! re-run the bake.",
        "",
        "/// 14x13 glyphs for ASCII 32-126. Each char = 13 u16 rows,",
        "/// bits 13-0 = pixel columns left-to-right.",
        "pub(crate) const GLYPHS: [[u16; 13]; 95] = [",
    ]
    advs = []
    for i, (rows, adv) in enumerate(glyphs):
        ch = chr(i + 32)
        name = "space" if i == 0 else ch
        body = ",".join(str(r) for r in rows)
        lines.append(f"    [{body}], {' ' * max(1, 62 - len(body))}// {i + 32} {name}")
        advs.append(str(adv))
    lines.append("];")
    lines.append("")
    lines.append("/// Per-glyph advance: the glyph's ink plus a pixel of")
    lines.append("/// air, so text tracks tight instead of monospaced.")
    lines.append(f"pub(crate) const ADVANCES: [u8; 95] = [{','.join(advs)}];")
    lines.append("")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(lines))

if __name__ == "__main__":
    g = bake()
    emit(g)
    advs = [a for _, a in g]
    print(f"wrote {OUT}")
    print(f"advances: min {min(advs)} max {max(advs)} "
          f"mean {sum(advs) / len(advs):.1f}")
