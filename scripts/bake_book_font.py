#!/usr/bin/env python3
"""Bake the body face table from IM Fell English (OFL, Google Fonts -
scripts/fonts/IMFellEnglish.ttf, licence in scripts/fonts/OFL-IMFell.txt).

The game's two hands, in the manuscript sense: Jacquarda's blackletter is
the rubric (titles, section heads, the words you don't read often), and
this - a Fell-type text face, the 17th-century book hand - is the plain
letter the body sets in. It's baked at 13px into the same 14x13 cells as
the rubric so every layout that was measured for the blackletter holds
its shape, and it carries the same per-glyph advance.

Only 'Q' outspans the cell: its famous swash tail runs past 14 columns.
The tail is clipped rather than the glyph squeezed - a crushed Q reads
worse than a short-tailed one. Output is game2-core/src/engine/glyphs_book.rs.

The conversation box sets its text a tier up (#1602): the same face at
20px into 22x20 cells, emitted as glyphs_book_big.rs - run with --big.
"""
import argparse
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "scripts", "fonts", "IMFellEnglish.ttf")


def bake(size, y0, y1, gw, thresh, gap, space_adv, min_adv):
    font = ImageFont.truetype(TTF, size)
    cw = y1 - y0
    glyphs = []
    for c in range(32, 127):
        im = Image.new("L", (96, 64), 0)
        ImageDraw.Draw(im).text((8, 0), chr(c), font=font, fill=255)
        im = im.point(lambda p: 255 if p >= thresh else 0)
        b = im.getbbox()
        rows = [0] * cw
        adv = space_adv if c == 32 else min_adv
        if b:
            ink_w = min(b[2] - b[0], gw)  # Q's tail clips at the cell edge
            ink = im.crop((b[0], y0, b[0] + ink_w, y1))
            px = ink.load()
            for y in range(cw):
                for x in range(ink_w):
                    if px[x, y]:
                        rows[y] |= 1 << (gw - 1 - x)
            if c != 32:
                adv = max(min_adv, ink_w + gap)
        glyphs.append((rows, adv))
    return glyphs


def emit(glyphs, out, name, size, y0, y1, gw):
    cw = y1 - y0
    word = "u16" if gw <= 16 else "u32"
    lines = [
        "//! GENERATED by scripts/bake_book_font.py - IM Fell English (OFL),",
        f"//! a {size}px text face baked into {gw}x{cw} cells, each glyph",
        "//! with its own advance. Do not edit by hand; re-run the bake.",
        "",
        f"/// {gw}x{cw} book glyphs for ASCII 32-126. Each char = {cw} {word} rows,",
        f"/// bits {gw - 1}-0 = pixel columns left-to-right.",
        f"pub(crate) const {name}_GLYPHS: [[{word}; {cw}]; 95] = [",
    ]
    advs = []
    for i, (rows, adv) in enumerate(glyphs):
        ch = chr(i + 32)
        label = "space" if i == 0 else ch
        body = ",".join(str(r) for r in rows)
        lines.append(f"    [{body}], {' ' * max(1, 62 - len(body))}// {i + 32} {label}")
        advs.append(str(adv))
    lines.append("];")
    lines.append("")
    lines.append("/// Per-glyph advance: the glyph's ink plus a pixel of air.")
    lines.append(f"pub(crate) const {name}_ADVANCES: [u8; 95] = [{','.join(advs)}];")
    lines.append("")
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--big", action="store_true",
                    help="the conversation box's 150%% tier (#1602): 20px into 22x20 cells, "
                         "u32 rows, glyphs_book_big.rs")
    a = ap.parse_args()
    if a.big:
        out = os.path.join(ROOT, "game2-core", "src", "engine", "glyphs_book_big.rs")
        g = bake(size=20, y0=5, y1=25, gw=22, thresh=110, gap=2, space_adv=6, min_adv=4)
        emit(g, out, "BOOK_BIG", size=20, y0=5, y1=25, gw=22)
    else:
        out = os.path.join(ROOT, "game2-core", "src", "engine", "glyphs_book.rs")
        # 13px; its full ink band is rows 3..16 - keeps descenders, clips a 1px serif tip
        g = bake(size=13, y0=3, y1=16, gw=14, thresh=110, gap=1, space_adv=4, min_adv=3)
        emit(g, out, "BOOK", size=13, y0=3, y1=16, gw=14)
    advs = [a for _, a in g]
    print(f"wrote {out}")
    print(f"advances: min {min(advs)} max {max(advs)} "
          f"mean {sum(advs) / len(advs):.1f}")
